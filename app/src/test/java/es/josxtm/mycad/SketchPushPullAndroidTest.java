 private void two(int action,float x,float y,float secondX,float secondY){
  MotionEvent.PointerProperties[] properties=new MotionEvent.PointerProperties[2];
  MotionEvent.PointerCoords[] coords=new MotionEvent.PointerCoords[2];
  for(int i=0;i<2;i++){
   properties[i]=new MotionEvent.PointerProperties();properties[i].id=i;
   properties[i].toolType=MotionEvent.TOOL_TYPE_FINGER;
   coords[i]=new MotionEvent.PointerCoords();coords[i].x=i==0?x:secondX;
   coords[i].y=i==0?y:secondY;coords[i].pressure=1;coords[i].size=1;
  }
  time+=16;
  MotionEvent event=MotionEvent.obtain(downTime,time,action,2,properties,coords,0,0,1,1,0,0,0,0);
  try{assertTrue(app.scene.dispatchTouchEvent(event));}finally{event.recycle();}
 }
